// The dev runtime's file side, run by scriptc itself: a dev build's tables arrive as parsed
// JSON, and the watcher that applies them runs on the app's own timer. Node's tests can't see
// what scriptc lowers at run time, so this compiles a small program with scriptc and runs it.
//
//   node tests/dev-watch.ts

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const { compileApp } = await import("../compiler/compile.ts");
const { Diagnostics } = await import("../compiler/diagnostics.ts");
const { writeDevData } = await import("../compiler/build.ts");

let failed = 0;
function check(name: string, ok: boolean, detail = ""): void {
  if (!ok) failed++;
  console.log(`${ok ? "ok  " : "FAIL"} ${name}${ok || detail === "" ? "" : ` — ${detail}`}`);
}

const dir = mkdtempSync(join(tmpdir(), "native-dev-watch-"));
const appDir = join(dir, "app");
mkdirSync(appDir, { recursive: true });
writeFileSync(join(appDir, "index.html"), `<!doctype html>
<html>
  <head><title>Todos</title><style>.a { color: red }</style></head>
  <body><div id="box" class="a"><h1>Hello</h1></div></body>
</html>`);
const app = compileApp(join(appDir, "index.html"), new Diagnostics());
writeDevData(appDir, app);
const data = join(appDir, ".native", "dev.json");
const ctl = join(appDir, ".native", "dev.ctl");
const scripts = join(appDir, ".native", "dev-scripts.token");
const findings = join(appDir, ".native", "dev-findings.json");
// A relaunch leaves its token behind: a dev build must not read that as a new request.
writeFileSync(ctl, "first");

/** Imports the SDK's own modules, so this runs the code a dev build runs. */
const devWatch = JSON.stringify(join(ROOT, "runtime", "app", "dev-watch.ts"));
const mount = JSON.stringify(join(ROOT, "runtime", "app", "mount.ts"));
const probe = join(dir, "probe.ts");
writeFileSync(probe, `// Generated by tests/dev-watch.ts.
import { readFileSync, writeFileSync } from "node:fs";
import type { AppTables } from ${mount};
import { readTables, readToken, watchFiles } from ${devWatch};

const data = ${JSON.stringify(data)};
const ctl = ${JSON.stringify(ctl)};
const scripts = ${JSON.stringify(scripts)};
const findings = ${JSON.stringify(findings)};

// The tables are plain data in both the compiled executable and the recompiled file.
const compiled = JSON.parse(readFileSync(data, "utf8")) as AppTables;
const fallback = readTables({ dataFile: data + ".missing", data: "", ctlFile: "", ctl: "", scriptsFile: "", scripts: "", findingsFile: "", findings: "" }, compiled);
console.log("fallback", fallback.tags.length, fallback.rules.length, fallback.title);

const files = { dataFile: data, data: "", ctlFile: ctl, ctl: readToken(ctl), scriptsFile: scripts, scripts: readToken(scripts), findingsFile: findings, findings: readToken(findings) };
const first = readTables(files, compiled);
console.log("file", first.tags.length, first.tags[0], first.tags[first.tags.length - 1]);

// The first change writes the scripts token, whose callback writes the restart token, so each
// callback proves the one before it fired.
let reloads = 0;
let scriptRuns = 0;
let findingRuns = 0;
let restarts = 0;
watchFiles(
  files,
  () => {
    reloads++;
    writeFileSync(scripts, "s2");
  },
  () => {
    restarts++;
    console.log("poll", reloads, scriptRuns, findingRuns, restarts);
    process.exit(reloads === 1 && scriptRuns === 1 && findingRuns === 1 ? 0 : 1);
  },
  () => {
    scriptRuns++;
    writeFileSync(findings, '{"findings":[]}');
  },
  () => {
    findingRuns++;
    writeFileSync(ctl, "second");
  },
);
setTimeout(() => writeFileSync(data, "changed\\n"), 100);
setTimeout(() => {
  console.log("poll", reloads, scriptRuns, findingRuns, restarts);
  process.exit(1);
}, 2000);
`);

const scriptc = existsSync(join(ROOT, "node_modules", ".bin", "scriptc"))
  ? join(ROOT, "node_modules", ".bin", "scriptc")
  : "scriptc";
const run = spawnSync(scriptc, ["run", probe, "-o", join(dir, "probe.bin")], {
  encoding: "utf8",
  cwd: dir,
  timeout: 240_000,
});
const out = run.stdout ?? "";
if (run.status !== 0) {
  process.stderr.write(run.stdout ?? "");
  process.stderr.write(run.stderr ?? "");
}
const line = (name: string): string => {
  const m = new RegExp(`^${name} (.*)$`, "m").exec(out);
  return m === null ? "" : m[1].trim();
};
const nodes = String(app.stats.elements);

check("the program runs", run.status === 0, `exit ${run.status}\n${run.stderr ?? ""}`);
check("the compiled tables stand in when no file was written", line("fallback") === `${nodes} ${app.tables.rules.length} Todos`, line("fallback"));
check("the written tables parse as the same type", line("file") === `${nodes} ${app.tables.tags[0]} ${app.tables.tags[app.tables.tags.length - 1]}`, line("file"));
check("a changed tables file reloads once, then the scripts, then the coverage report, once each",
  line("poll") === "1 1 1 1", line("poll"));

console.log(failed === 0 ? "all passed" : `${failed} failed`);
process.exit(failed === 0 ? 0 : 1);
