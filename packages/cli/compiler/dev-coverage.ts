// `scriptc coverage` in native dev: what a release build would analyze, checked in the
// background after the island has run the app's new scripts. The island runs the app as Node
// does, so code the compiler refuses or cannot type still runs in dev; this is the report that
// says so before a release build does. It never blocks the reload: the analysis runs in a child
// process, its answer is reported when it arrives, and an edit that lands while it runs asks for
// one more pass.
//
// The project it analyzes is the app's own sources with the DOM names the build gives them
// (dom-globals.ts), under a tsconfig with the app's JSX settings — the closest cheap stand-in
// for the generated project a build compiles, without compiling or linking anything.

import { spawn } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import type { AppBuild } from "./build.ts";
import { findScriptc, jsxSettings, nodeTypesInstalled, prepareAnalysisProject } from "./build.ts";
import { domGlobalsModule } from "./dom-globals.ts";
import { importPath } from "./scripts.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const RUNTIME = join(ROOT, "runtime");

/** One thing the compiler reports about the app: an error, a warning, or a note. */
export interface CoverageFinding {
  code: string;
  severity: string;
  /** The file it is about, relative to the app directory when it is in it. */
  file: string;
  line: number;
  column: number;
  message: string;
}

export interface CoverageReport {
  /** The coverage command's own headline, e.g. "4 of 4 statements compile statically". */
  summary: string;
  findings: CoverageFinding[];
}

/** The directory the analysis reads: generated entry, DOM declarations and tsconfig. */
function projectDir(appDir: string): string {
  return join(appDir, ".native", "coverage");
}

/**
 * Writes the analysis project for the app and returns its entry, or null when the page has no
 * module scripts with files to analyze. The sources are imported where they sit, so the app's
 * own node_modules and tsconfig-visible packages resolve as they do in a build.
 */
export function writeCoverageProject(built: AppBuild): string | null {
  const appDir = built.appDir;
  const scripts = built.app.scripts.filter((s) => s.module && s.path !== null).map((s) => s.path!);
  const dir = projectDir(appDir);
  rmSync(dir, { recursive: true, force: true });
  if (scripts.length === 0) return null;
  mkdirSync(dir, { recursive: true });
  // The app's sources as a build writes them: copies whose DOM names are imports of the runtime's
  // own values (a build binds them that way; an app file run as a module would otherwise have no
  // `document` at all), and the dependencies they reach copied beside them.
  const srcOut = join(dir, "src");
  let jsxImportSource: string | null = null;
  try {
    jsxImportSource = prepareAnalysisProject(appDir, srcOut).jsxImportSource;
  } catch {
    // A JSX runtime that cannot be wired here is not the dev loop's to fail on: the analysis
    // falls back to the app's own import source.
  }
  const files = scripts.map((file) => join(srcOut, relative(appDir, file)));
  writeFileSync(join(dir, "dom-globals.ts"), domGlobalsModule(RUNTIME, nodeTypesInstalled(join(appDir, ".native"))));
  const entry = join(dir, "entry.ts");
  writeFileSync(entry, [
    "// Generated by native dev: the page's module scripts, typed the way the release build types",
    "// them (the DOM names come from the runtime's declarations, not a browser library).",
    'import "./dom-globals.ts";',
    ...files.map((file) => `import ${JSON.stringify(importPath(dir, file))};`),
    "",
  ].join("\n"));
  const jsx = jsxSettings(appDir, false);
  const compilerOptions: { [key: string]: string | boolean } = { jsx: jsx.jsx, strictNullChecks: true };
  if (jsx.jsx === "react") {
    compilerOptions.jsxFactory = jsx.jsxFactory;
    compilerOptions.jsxFragmentFactory = jsx.jsxFragmentFactory;
  } else {
    compilerOptions.jsxImportSource = jsxImportSource ?? jsx.jsxImportSource;
  }
  writeFileSync(join(dir, "tsconfig.json"),
    JSON.stringify({ files: ["./entry.ts"], compilerOptions }, null, 2) + "\n");
  return entry;
}

/** A finding's identity, for telling the ones an edit added from the ones already reported. */
export function findingKey(finding: CoverageFinding): string {
  return `${finding.code}:${finding.file}:${finding.line}:${finding.column}:${finding.message}`;
}

interface DiagnosticsJson {
  success?: boolean;
  stats?: { statementsTotal?: number; statementsStatic?: number; statementsDynamic?: number };
  groups?: {
    code?: string;
    severity?: string;
    message?: string;
    primary?: { file?: string; line?: number; column?: number };
  }[];
}

/** How long an analysis may run before it is killed: minutes on a large app, never 0. */
const COVERAGE_TIMEOUT_MS = 180_000;

/** Runs `scriptc coverage` on the entry in a child process. Answers null when the run could not
 *  happen at all (the compiler failed to start or was killed); the caller keeps the last answer. */
export async function runCoverage(appDir: string, entry: string, env: NodeJS.ProcessEnv,
  signal?: AbortSignal): Promise<CoverageReport | null> {
  return new Promise((answer) => {
    let stdout = "";
    let stderr = "";
    let settled = false;
    const done = (report: CoverageReport | null): void => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      answer(report);
    };
    let child;
    const scriptc = findScriptc();
    try {
      child = spawn(scriptc.command, [...scriptc.args, "coverage", entry, "--print=diagnostics"], {
        cwd: appDir,
        env,
        stdio: ["ignore", "pipe", "pipe"],
      });
    } catch {
      done(null);
      return;
    }
    const timer = setTimeout(() => {
      child.kill("SIGKILL");
      done(null);
    }, COVERAGE_TIMEOUT_MS);
    // A newer edit asks for a pass on newer sources: the one in flight is analysing code the
    // page no longer has.
    signal?.addEventListener("abort", () => {
      child.kill("SIGKILL");
      done(null);
    }, { once: true });
    child.stdout?.on("data", (chunk: Buffer) => {
      if (stdout.length < 4 * 1024 * 1024) stdout += chunk.toString("utf8");
    });
    child.stderr?.on("data", (chunk: Buffer) => {
      if (stderr.length < 1024 * 1024) stderr += chunk.toString("utf8");
    });
    child.on("error", () => done(null));
    child.on("close", () => {
      const start = stdout.indexOf("{");
      if (start < 0) {
        done(null);
        return;
      }
      let json: DiagnosticsJson;
      try {
        json = JSON.parse(stdout.slice(start)) as DiagnosticsJson;
      } catch {
        done(null);
        return;
      }
      // The app's own files only: the analysis also compiles the SDK runtime and the app's
      // dependencies, whose warnings are not the app author's to fix in a dev loop.
      const findings: CoverageFinding[] = [];
      for (const group of json.groups ?? []) {
        const primary = group.primary ?? {};
        const shown = appFileOf(appDir, primary.file ?? "");
        if (shown === null) continue;
        findings.push({
          code: group.code ?? "",
          severity: group.severity ?? "error",
          file: shown,
          line: primary.line ?? 0,
          column: primary.column ?? 0,
          message: group.message ?? "",
        });
      }
      const stats = json.stats;
      const summary = stats === undefined || stats.statementsTotal === undefined
        ? (json.success === false ? "not analyzable" : "")
        : `${stats.statementsStatic ?? 0} of ${stats.statementsTotal} statements compile statically` +
          (stats.statementsDynamic !== undefined && stats.statementsDynamic > 0 ? `, ${stats.statementsDynamic} in the dynamic tier` : "");
      done({ summary, findings });
    });
  });
}

/** A file as the app author names it (relative to the app directory), or null for a file that is
 *  not the app's: the SDK runtime, a package, or a copy the analysis project made of a source. */
function appFileOf(appDir: string, file: string): string | null {
  if (file === "") return null;
  const inside = relative(appDir, file);
  if (inside === "" || inside.startsWith("..") || isAbsolute(inside)) return null;
  const parts = inside.split(sep);
  if (parts.includes("node_modules")) return null;
  // The analysis compiles copies under .native/coverage/src; the finding belongs to the source.
  const copy = join(".native", "coverage", "src") + sep;
  const shown = inside.startsWith(copy) ? inside.slice(copy.length) : inside;
  const portable = shown.split(sep).join("/");
  // The build vendors the app's dependencies beside its sources; their warnings are not the
  // app author's to fix in a dev loop.
  if (portable.startsWith("deps/")) return null;
  return portable;
}
