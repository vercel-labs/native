// The app's scripts as one bundle for `native dev`'s island mode. The page's scripts run on
// Node's JavaScript engine in the dev host, against the compiled DOM, so the bundle is what the
// island runs: esbuild resolves the app's imports from its own node_modules and writes a source
// map, so an exception points at the developer's TypeScript lines.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { context, type BuildContext, type BuildOptions } from "esbuild";
import type { AppBuild } from "./build.ts";
import { jsxSettings } from "./build.ts";
import { importPath } from "./scripts.ts";

export interface ScriptBundler {
  /** The bundle's file: what the host runs, and the source map's referent. */
  readonly bundle: string;
  /** Rewrites the bundle's sources from `build` and rebuilds it; `errors` is "" when it compiled. */
  rebuild(build: AppBuild): Promise<{ ms: number; errors: string }>;
  dispose(): Promise<void>;
}

/** esbuild's errors as the lines a compiler prints: file:line:column: message. */
function errorText(err: unknown): string {
  const errors = (err as { errors?: { text: string; location?: { file: string; line: number; column: number } | null }[] }).errors;
  if (errors === undefined || errors.length === 0) return err instanceof Error ? err.message : String(err);
  return errors
    .map((e) => {
      const at = e.location;
      return at === null || at === undefined ? e.text : `${at.file}:${at.line}:${at.column}: ${e.text}`;
    })
    .join("\n");
}

/**
 * Writes the files the bundle is made of, from one build of the page, and answers the entry
 * esbuild bundles. It runs again before every rebuild: a classic script is concatenated here, and
 * its path doesn't change as its text does, so an edited classic script only reaches the bundle
 * when this is written again.
 *
 * Module scripts are entry points in document order; an inline script is written beside the
 * bundle first. Classic scripts share one scope in a browser, so they are concatenated into one
 * file, as the compiled build writes them. The page's inline handler attributes become calls to
 * `__nativeAttachHandler`, which the host installs from the runtime's `attachHandler`.
 */
function writeScriptSources(built: AppBuild): string {
  const dir = join(built.appDir, ".native");
  mkdirSync(dir, { recursive: true });
  const imports: string[] = [];
  const handlers = built.app.handlers;
  if (handlers.length > 0) {
    const file = join(dir, "dev-handlers.js");
    const lines = ["// Generated by native: the page's inline event handler attributes, in document order."];
    for (const h of handlers) {
      lines.push(`__nativeAttachHandler(${h.node}, ${JSON.stringify(h.type)}, function (event) {`);
      lines.push(h.code);
      lines.push("});");
    }
    writeFileSync(file, lines.join("\n") + "\n");
    imports.push(file);
  }
  const classic = built.app.scripts.filter((s) => !s.module);
  if (classic.length > 0) {
    // A classic script may be TypeScript: an external `.ts` file, and an inline `<script>` is
    // compiled as one. esbuild picks its parser from the extension and reads a `.js` file as
    // JavaScript alone, so the concatenated scripts take a `.ts` name unless every one of them is
    // an external JavaScript file. `.tsx` keeps a classic `.tsx` script's JSX parseable.
    const paths = classic.flatMap((s) => (s.path === null ? [] : [s.path]));
    const jsx = paths.some((path) => /\.[cm]?[jt]sx$/.test(path));
    const types = paths.length < classic.length || paths.some((path) => /\.[cm]?tsx?$/.test(path));
    const file = join(dir, jsx ? "dev-classic.tsx" : types ? "dev-classic.ts" : "dev-classic.js");
    // One scope, in document order, as the compiled build's classic bundle: an app that puts
    // several classic scripts on one page has them see each other's declarations.
    writeFileSync(file, classic.map((s) => s.text).join("\n;\n") + "\n");
    imports.push(file);
  }
  let inline = 0;
  for (const s of built.app.scripts) {
    if (!s.module) continue;
    if (s.path !== null) {
      imports.push(s.path);
      continue;
    }
    // scriptc parses a `.js` file as TypeScript, so an inline script may carry annotations; the
    // `.ts` name gives esbuild the same parser.
    const file = join(dir, `dev-inline-${inline++}.ts`);
    writeFileSync(file, s.text);
    imports.push(file);
  }
  const entry = join(dir, "dev-entry.js");
  writeFileSync(entry, [
    "// Generated by native dev: the page's scripts, in document order.",
    ...imports.map((file) => `import ${JSON.stringify(importPath(dir, file))};`),
    "",
  ].join("\n"));
  return entry;
}

/**
 * Builds the esbuild context that bundles the page's scripts into `.native/dev-bundle.js`, and
 * writes that bundle's sources from `built`. Each rebuild takes the build it is given, so an
 * edit to any of the page's scripts — a concatenated classic one included — is what runs next.
 */
/** The options every dev bundle is built with, whatever its JSX mode. */
function bundleOptions(entry: string, bundle: string, appDir: string): BuildOptions {
  return {
    entryPoints: [entry],
    outfile: bundle,
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2023",
    // Node builtins and native addons stay loads rather than becoming bundle-time errors: the
    // island installs Node's require and scriptc's load hook before the bundle runs, so a
    // module a build refuses is refused here, with the compiler's own diagnostic.
    external: ["node:*", "*.node"],
    sourcemap: "linked",
    logLevel: "silent",
    absWorkingDir: appDir,
    define: { "process.env.NODE_ENV": '"development"' },
  };
}

export async function createScriptBundler(built: AppBuild): Promise<ScriptBundler> {
  const appDir = built.appDir;
  const entry = writeScriptSources(built);
  const jsx = jsxSettings(appDir, true);
  const automatic = jsx.jsx !== "react";
  const bundle = join(appDir, ".native", "dev-bundle.js");
  // Each JSX mode is its own object literal: the bundle is built by the compiled CLI too, and
  // scriptc reads an object literal's shape at compile time, so the options can't be assigned
  // afterwards or spread from a conditional.
  const options: BuildOptions = automatic
    ? {
        ...bundleOptions(entry, bundle, appDir),
        jsx: "automatic",
        jsxImportSource: jsx.jsxImportSource,
        jsxDev: jsx.jsx === "react-jsxdev",
      }
    : {
        ...bundleOptions(entry, bundle, appDir),
        jsx: "transform",
        jsxFactory: jsx.jsxFactory,
        jsxFragment: jsx.jsxFragmentFactory,
      };
  let ctx: BuildContext | null = await context(options);

  return {
    bundle,
    async rebuild(build: AppBuild) {
      const started = performance.now();
      if (ctx === null) return { ms: performance.now() - started, errors: "the bundler was disposed" };
      writeScriptSources(build);
      try {
        await ctx.rebuild();
        return { ms: performance.now() - started, errors: "" };
      } catch (err) {
        return { ms: performance.now() - started, errors: errorText(err) };
      }
    },
    async dispose() {
      const current = ctx;
      ctx = null;
      if (current !== null) await current.dispose();
    },
  };
}
